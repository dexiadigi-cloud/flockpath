// English is the fallback for any key missing in the other
// language, so a half-translated language never shows a blank.
export function t(lang, key) {
  const table = STRINGS[lang] ?? STRINGS.en;
  return table[key] ?? STRINGS.en[key] ?? key;
}

// tf() is t() with {name} placeholders filled in, for
// strings that carry a count, a name, or a reference.
export function tf(lang, key, vars) {
  let s = t(lang, key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
